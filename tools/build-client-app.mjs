#!/usr/bin/env node
// tools/build-client-app.mjs — materialize the *server-served* client into one self-contained folder that the desktop
// (Electron) and Android (Capacitor) wrappers ship (docs/APP.md).
//
// The game server hands the browser five things (server/index.js `createStaticHandler`):
//   /          public/            index.html, js, css, vendor, fonts, assets…
//   /data/     data/              the generated game data (the client reads it, the sim freezes it)
//   /shared/   shared/            ES modules shared by the server and the browser
//   /sim/      server/sim/        the battle simulation the browser runs (client-side combat, DESIGN §14) — `.js`
//                                 only and minus the Node-only loader
//   /data.js   DATA_SHIM_JS       the browser stand-in of server/data.js, generated by the server
// A packaged client carries a copy of exactly that, so the only thing it still needs the server for is the WebSocket
// (rooms, rounds, economy) — which is where the wrapper config comes in: the tool injects
// `window.__SP_APP__ = { kind, version, server }` into index.html, and the settings let a player point it elsewhere
// (public/js/serverConfig.js).
//
// What is left out on purpose: `dev/` (the browser mock / render demo pages of public/, only useful when developing
// against the real server) and `download/` (installers published next to the game, docs/APP.md) — neither belongs in
// an app bundle.
//
// Usage: node tools/build-client-app.mjs [--out app/build/client] [--kind desktop|android|web]
//                                      [--server http://host:3000] [--slim] [--quiet]
//   --slim   leave out public/assets/audio/voice (58 MB): the app then asks the server for voice lines on demand

import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DATA_SHIM_JS } from '../server/index.js';
import { APP_VERSION } from '../shared/constants.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const HELP = `Usage: node tools/build-client-app.mjs [options]
  --out <dir>       output folder (default app/build/client)
  --kind <k>        desktop | android | web (default desktop; written into window.__SP_APP__.kind)
  --server <url>    game server the app connects to (default '' = same origin, i.e. a browser build)
  --slim            skip public/assets/audio/voice (58 MB; the app fetches voice from the server when it is there)
  --quiet           only the summary
  --help`;

function parseArgs(argv) {
  const o = { out: 'app/build/client', kind: 'desktop', server: '', slim: false, quiet: false, help: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const [k, v] = a.split('=');
    if (k === '--out') o.out = v ?? argv[++i];
    else if (k === '--kind') o.kind = v ?? argv[++i];
    else if (k === '--server') o.server = v ?? argv[++i];
    else if (k === '--slim') o.slim = true;
    else if (k === '--quiet') o.quiet = true;
    else if (k === '--help' || k === '-h') o.help = true;
    else throw new Error(`unknown option ${a}\n${HELP}`);
  }
  // --out is relative to the caller's working directory (npm scripts in app/desktop and app/android pass ../build/client
  // and www), and an absolute path is taken as is.
  o.out = path.resolve(process.cwd(), o.out);
  return o;
}

const mb = (n) => `${(n / 1048576).toFixed(1)} MB`;

/** Recursive size + file count of a folder (missing ⇒ zeros). */
async function measure(dir) {
  let bytes = 0, files = 0;
  const walk = async (d) => {
    let ents = [];
    try { ents = await fsp.readdir(d, { withFileTypes: true }); } catch { return; }
    for (const e of ents) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) await walk(p);
      else if (e.isFile()) { files++; try { bytes += (await fsp.stat(p)).size; } catch { /* ignore */ } }
    }
  };
  await walk(dir);
  return { bytes, files };
}

/**
 * Copy a tree, optionally filtering entries.
 * @param {string} from
 * @param {string} to
 * @param {(rel: string, isDir: boolean) => boolean} [keep] relative POSIX path filter
 */
async function copyTree(from, to, keep = () => true) {
  const walk = async (src, dst, rel) => {
    let ents = [];
    try { ents = await fsp.readdir(src, { withFileTypes: true }); } catch { return; }
    await fsp.mkdir(dst, { recursive: true });
    for (const e of ents) {
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (!keep(r, e.isDirectory())) continue;
      const s = path.join(src, e.name), d = path.join(dst, e.name);
      if (e.isDirectory()) await walk(s, d, r);
      else if (e.isFile()) await fsp.copyFile(s, d);
    }
  };
  await walk(from, to, '');
}

/** Insert the wrapper config as the first script of index.html (before every module the app loads). */
function injectConfig(html, cfg) {
  const tag = `<script>window.__SP_APP__=${JSON.stringify(cfg)};</script>`;
  const i = html.search(/<script\b/i);
  if (i >= 0) return html.slice(0, i) + tag + '\n    ' + html.slice(i);
  const j = html.search(/<\/head>/i);
  if (j >= 0) return html.slice(0, j) + '  ' + tag + '\n' + html.slice(j);
  return tag + '\n' + html;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) { console.log(HELP); return 0; }
  const log = opts.quiet ? () => {} : (m) => console.log(m);
  const t0 = Date.now();
  log(`[client] root ${ROOT}`);

  const required = ['public/index.html', 'data/chess.json', 'shared/protocol.js', 'server/sim/spec.js'];
  for (const r of required) {
    if (!fs.existsSync(path.join(ROOT, r))) throw new Error(`missing ${r} — is this the project root? (run npm ci / npm run setup)`);
  }

  await fsp.rm(opts.out, { recursive: true, force: true });
  await fsp.mkdir(opts.out, { recursive: true });

  // /  ← public/   (--slim drops the voice pack: 58 MB of lazily-played lines; dev/ and download/ never ship)
  const NEVER = ['dev', 'download'];
  const VOICE = 'assets/audio/voice';
  const keepPublic = (rel) => {
    if (NEVER.includes(rel) || NEVER.some((n) => rel.startsWith(`${n}/`))) return false;
    // --slim drops the whole voice pack (the directory entry and every file under it)
    if (opts.slim && (rel === VOICE || rel.startsWith(`${VOICE}/`))) return false;
    return true;
  };
  await copyTree(path.join(ROOT, 'public'), opts.out, (rel) => keepPublic(rel));
  log(`[client] public/ → /`);
  await copyTree(path.join(ROOT, 'data'), path.join(opts.out, 'data'));
  log(`[client] data/ → /data/`);
  await copyTree(path.join(ROOT, 'shared'), path.join(opts.out, 'shared'));
  log(`[client] shared/ → /shared/`);
  // /sim/ ← server/sim: `.js` only, minus the Node-only loader (server/index.js SIM_PRIVATE)
  await copyTree(path.join(ROOT, 'server', 'sim'), path.join(opts.out, 'sim'),
    (rel, isDir) => (isDir ? true : rel.endsWith('.js') && rel.toLowerCase() !== 'nodedata.js'));
  log(`[client] server/sim/ → /sim/ (.js only)`);
  await fsp.writeFile(path.join(opts.out, 'data.js'), DATA_SHIM_JS);
  log(`[client] server/data.js stand-in → /data.js`);

  // wrapper config: which server this build talks to
  const cfg = { kind: opts.kind, version: APP_VERSION, server: opts.server || '' };
  const indexPath = path.join(opts.out, 'index.html');
  const html = await fsp.readFile(indexPath, 'utf8');
  if (html.includes('window.__SP_APP__')) throw new Error('index.html already carries a wrapper config');
  await fsp.writeFile(indexPath, injectConfig(html, cfg));
  log(`[client] index.html: window.__SP_APP__=${JSON.stringify(cfg)}`);

  const { bytes, files } = await measure(opts.out);
  const voice = await measure(path.join(opts.out, 'assets', 'audio', 'voice'));
  console.log(`[client] ${opts.out}`);
  console.log(`[client] ${files} files, ${mb(bytes)}` + (voice.files ? ` (voice: ${voice.files} files, ${mb(voice.bytes)}${opts.slim ? ' — skipped' : ''})` : ''));
  console.log(`[client] kind=${cfg.kind} server=${cfg.server || '(same origin)'}  ·  ${((Date.now() - t0) / 1000).toFixed(1)} s`);
  return 0;
}

main().then((c) => process.exit(c), (err) => { console.error(`[client] ${err.message}`); process.exit(1); });
